"""Эксперимент с контрольной группой (S4): «всегда ищем» против «модель решает».

Контроль — нынешний режим ассистента: вопрос всегда разбирается в поиск
(`ANSWER_MODE=always`). Тест — модель сама решает, искать ли
(`ANSWER_MODE=auto`). Выключатель — `EXPERIMENT` (по умолчанию выключен,
решение 87): без него все пользователи в контроле.

Группа — по псевдониму пользователя из журнала (HMAC-SHA256 от chat_id на
JOURNAL_KEY, `journal.py`): чётный — контроль, нечётный — тест. Так
распределение:
- постоянное: человек всегда в одной группе, и его ответы сравнимы;
- случайное по сути: HMAC от chat_id не связан ни с тем, кто человек, ни с
  тем, что он спрашивает;
- воспроизводимое: по журналу видно, в какой группе каждое событие.

Метрика и анализ — `evals/experiment.py`: единица анализа — пользователь,
как и единица распределения.
"""

from typing import Literal

Arm = Literal["always", "auto"]
CONTROL: Arm = "always"
TEST: Arm = "auto"


def arm(pseudonym: str) -> Arm:
    """Группа по псевдониму из журнала (12 hex-символов HMAC)."""
    return TEST if int(pseudonym, 16) % 2 else CONTROL
